# Regenerates requirements.txt and build-constraints.txt, the hash-locked
# dependency set the Dockerfile installs. It resolves for CPython 3.12 on
# linux/amd64 and linux/arm64, each restricted to manylinux_2_31 wheels (glibc
# 2.31), and fails when the two resolutions differ, because the Dockerfile
# installs one file on both. Needs uv.
#
#   ./lock.sh
set -euo pipefail
cd "$(dirname "$0")"

INDEX_URL=${INDEX_URL:-https://pypi.org/simple}
tmp=$(mktemp -d)
trap 'rm -rf "${tmp}"' EXIT

compile() { # compile <in> <out> [uv args...]
  local in=$1 out=$2
  shift 2
  uv pip compile --quiet --no-header --generate-hashes --index-url "${INDEX_URL}" \
    --python-version 3.12 "$@" "${in}" -o "${out}"
}

for arch in x86_64 aarch64; do
  compile requirements.in "${tmp}/${arch}.txt" --python-platform "${arch}-manylinux_2_31"
done
if ! diff -q "${tmp}/x86_64.txt" "${tmp}/aarch64.txt" >/dev/null; then
  diff "${tmp}/x86_64.txt" "${tmp}/aarch64.txt" >&2 || true
  echo "lock.sh: amd64 and arm64 resolve differently; split requirements.txt per architecture" >&2
  exit 1
fi
compile build-constraints.in "${tmp}/build.txt"

header='# Generated by ./lock.sh from %s for CPython 3.12, linux/amd64 and
# linux/arm64, manylinux_2_31. Do not edit; run ./lock.sh.
'
# shellcheck disable=SC2059 # the header is the format
{ printf "${header}" requirements.in; cat "${tmp}/x86_64.txt"; } >requirements.txt
# shellcheck disable=SC2059
{ printf "${header}" build-constraints.in; cat "${tmp}/build.txt"; } >build-constraints.txt
echo "wrote requirements.txt ($(grep -c '==' requirements.txt) packages) and build-constraints.txt"
